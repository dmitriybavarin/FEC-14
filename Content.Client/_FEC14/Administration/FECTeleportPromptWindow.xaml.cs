using JetBrains.Annotations;
using Robust.Client.AutoGenerated;
using Robust.Client.Console;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.IoC;
using Robust.Shared.Utility;

namespace Content.Client._FEC14.Administration;

[GenerateTypedNameReferences]
[UsedImplicitly]
public sealed partial class FECTeleportPromptWindow : DefaultWindow
{
    public FECTeleportPromptWindow()
    {
        RobustXamlLoader.Load(this);
        GoButton.OnPressed += _ => Submit();
        TargetEdit.OnTextEntered += _ => Submit();
    }

    private void Submit()
    {
        var target = TargetEdit.Text.Trim();
        if (target.Length == 0)
            return;

        IoCManager.Resolve<IClientConsoleHost>().ExecuteCommand($"fectp \"{CommandParsing.Escape(target)}\"");
    }
}
