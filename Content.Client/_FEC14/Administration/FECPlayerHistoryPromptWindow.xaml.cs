using JetBrains.Annotations;
using Robust.Client.AutoGenerated;
using Robust.Client.Console;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.IoC;
using Robust.Shared.Utility;

namespace Content.Client._FEC14.Administration;

[GenerateTypedNameReferences]
[UsedImplicitly]
public sealed partial class FECPlayerHistoryPromptWindow : DefaultWindow
{
    public FECPlayerHistoryPromptWindow()
    {
        RobustXamlLoader.Load(this);
        OpenButton.OnPressed += _ => Submit();
        PlayerEdit.OnTextEntered += _ => Submit();
    }

    private void Submit()
    {
        var name = PlayerEdit.Text.Trim();
        if (name.Length == 0)
            return;

        IoCManager.Resolve<IClientConsoleHost>().ExecuteCommand($"playerhistory \"{CommandParsing.Escape(name)}\"");
        Close();
    }
}
