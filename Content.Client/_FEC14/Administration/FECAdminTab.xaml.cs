using Content.Client.Administration.Managers;
using Content.Shared._FEC14.Administration;
using Content.Shared.Administration;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client._FEC14.Administration;

[GenerateTypedNameReferences]
public sealed partial class FECAdminTab : Control
{
    [Dependency] private readonly IClientAdminManager _admin = default!;
    [Dependency] private readonly IEntityManager _entities = default!;

    public FECAdminTab()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        TabContainer.SetTabTitle(ToolsTab, Loc.GetString("fec-admin-tab-tools"));
        TabContainer.SetTabTitle(SettingsTab, Loc.GetString("fec-admin-category-settings"));

        HintLabel.SetMessage(FormattedMessage.FromMarkupOrThrow($"[color=#A0A0A0]{FormattedMessage.EscapeText(Loc.GetString("fec-settings-hint"))}[/color]"));
        RefreshButton.OnPressed += _ => Request();
        Settings.OnSet += (key, value) => _entities.System<FECSettingsSystem>().Set(key, value);
        Settings.OnReset += key => _entities.System<FECSettingsSystem>().Reset(key);
    }

    protected override void EnteredTree()
    {
        base.EnteredTree();
        _entities.System<FECSettingsSystem>().StateReceived += OnState;
        Request();
    }

    protected override void ExitedTree()
    {
        base.ExitedTree();
        _entities.System<FECSettingsSystem>().StateReceived -= OnState;
    }

    private void Request()
    {
        var access = _admin.HasFlag(AdminFlags.Server);
        NoAccessLabel.Visible = !access;
        Settings.Visible = access;
        RefreshButton.Visible = access;
        if (access)
            _entities.System<FECSettingsSystem>().Request();
    }

    private void OnState(FECSettingsStateEvent ev)
    {
        Settings.Update(ev.Entries, ev.Status);
    }
}
