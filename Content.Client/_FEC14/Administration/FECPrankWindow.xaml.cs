using JetBrains.Annotations;
using Robust.Client.AutoGenerated;
using Robust.Client.Console;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.IoC;
using Robust.Shared.Utility;

namespace Content.Client._FEC14.Administration;

[GenerateTypedNameReferences]
[UsedImplicitly]
public sealed partial class FECPrankWindow : DefaultWindow
{
    private static readonly string[] Pranks = { "say", "honk", "balloon", "spin" };

    public FECPrankWindow()
    {
        RobustXamlLoader.Load(this);
        for (var i = 0; i < Pranks.Length; i++)
        {
            PrankSelector.AddItem(Loc.GetString($"fec-prank-{Pranks[i]}"), i);
        }

        PrankSelector.OnItemSelected += args => PrankSelector.SelectId(args.Id);
        GoButton.OnPressed += _ => Submit();
        PlayerEdit.OnTextEntered += _ => Submit();
    }

    private void Submit()
    {
        var player = PlayerEdit.Text.Trim();
        if (player.Length == 0)
            return;

        var prank = Pranks[PrankSelector.SelectedId];
        IoCManager.Resolve<IClientConsoleHost>().ExecuteCommand($"fecprank \"{CommandParsing.Escape(player)}\" {prank}");
    }
}
